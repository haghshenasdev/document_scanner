import 'package:image/image.dart' as img;

enum ScanFilter { original, document, sharp, grayscale, blackWhite, magicColor }

class ImageEnhancer {
  // ===========================================================================
  // Public API
  // ===========================================================================

  static img.Image apply(img.Image source, ScanFilter filter) {
    switch (filter) {
      // =======================================================================
      // ORIGINAL
      // =======================================================================
      //
      // قبلاً اینجا copyResize انجام می‌شد:
      //
      // img.copyResize(
      //   source,
      //   width: source.width,
      //   height: source.height,
      // )
      //
      // که عملاً یک کپی کامل از چند میلیون پیکسل ایجاد می‌کرد.
      //
      // هیچ‌کدام از فیلترها source را در این حالت تغییر نمی‌دهند،
      // بنابراین نیازی به کپی نداریم.
      // =======================================================================

      case ScanFilter.original:
        return source;

      // =======================================================================
      // DOCUMENT
      // =======================================================================

      case ScanFilter.document:
        return _document(source);

      // =======================================================================
      // SHARP
      // =======================================================================

      case ScanFilter.sharp:
        return _sharp(source);

      // =======================================================================
      // GRAYSCALE
      // =======================================================================

      case ScanFilter.grayscale:
        return img.grayscale(source);

      // =======================================================================
      // BLACK & WHITE
      // =======================================================================

      case ScanFilter.blackWhite:
        return _blackWhite(source);

      // =======================================================================
      // MAGIC COLOR
      // =======================================================================

      case ScanFilter.magicColor:
        return _magicColor(source);
    }
  }

  // ===========================================================================
  // DOCUMENT
  // ===========================================================================

  static img.Image _document(img.Image image) {
    // -------------------------------------------------------------------------
    // افزایش کنتراست و روشنایی
    // -------------------------------------------------------------------------

    var result = img.adjustColor(
      image,
      contrast: 1.15,
      brightness: 1.04,
      saturation: 0.92,
    );

    // -------------------------------------------------------------------------
    // سفیدتر کردن کاغذ
    // -------------------------------------------------------------------------

    result = _whitenPaper(result, strength: 0.20);

    // -------------------------------------------------------------------------
    // شارپ ملایم
    // -------------------------------------------------------------------------
    //
    // Kernel کوچک 3x3 است و نسبتاً سریع است.
    // -------------------------------------------------------------------------

    result = img.convolution(
      result,
      filter: const [0, -1, 0, -1, 5, -1, 0, -1, 0],
    );

    return result;
  }

  // ===========================================================================
  // SHARP
  // ===========================================================================

  static img.Image _sharp(img.Image image) {
    var result = img.adjustColor(image, contrast: 1.12, brightness: 1.02);

    result = img.convolution(
      result,
      filter: const [0, -1, 0, -1, 5.5, -1, 0, -1, 0],
    );

    return result;
  }

  // ===========================================================================
  // GRAYSCALE
  // ===========================================================================

  static img.Image _grayscale(img.Image image) {
    return img.grayscale(image);
  }

  // ===========================================================================
  // BLACK & WHITE
  // ===========================================================================

  static img.Image _blackWhite(img.Image image) {
    // -------------------------------------------------------------------------
    // Grayscale
    // -------------------------------------------------------------------------

    var result = img.grayscale(image);

    // -------------------------------------------------------------------------
    // افزایش کنتراست
    // -------------------------------------------------------------------------

    result = img.adjustColor(result, contrast: 1.35, brightness: 1.05);

    // -------------------------------------------------------------------------
    // Threshold
    // -------------------------------------------------------------------------
    //
    // به جای چند عملیات اضافه، مستقیماً روی پیکسل‌ها کار می‌کنیم.
    // -------------------------------------------------------------------------

    for (final pixel in result) {
      final luminance = pixel.luminance;

      if (luminance > 185) {
        pixel.r = 255;
        pixel.g = 255;
        pixel.b = 255;
      } else {
        pixel.r = 0;
        pixel.g = 0;
        pixel.b = 0;
      }
    }

    return result;
  }

  // ===========================================================================
  // MAGIC COLOR
  // ===========================================================================

  static img.Image _magicColor(img.Image image) {
    var result = img.adjustColor(
      image,
      brightness: 1.05,
      contrast: 1.10,
      saturation: 0.95,
    );

    result = _whitenPaper(result, strength: 0.12);

    result = img.convolution(
      result,
      filter: const [0, -1, 0, -1, 5, -1, 0, -1, 0],
    );

    return result;
  }

  // ===========================================================================
  // PAPER WHITENING
  // ===========================================================================

  static img.Image _whitenPaper(img.Image image, {double strength = 0.15}) {
    // -------------------------------------------------------------------------
    // مقدار strength را یک بار آماده می‌کنیم.
    // -------------------------------------------------------------------------

    final s = strength;

    // -------------------------------------------------------------------------
    // روی تمام پیکسل‌ها فقط یک بار عبور می‌کنیم.
    // -------------------------------------------------------------------------

    for (final pixel in image) {
      final r = pixel.r;
      final g = pixel.g;
      final b = pixel.b;

      // -----------------------------------------------------------------------
      // Luminance
      // -----------------------------------------------------------------------

      final luminance = 0.299 * r + 0.587 * g + 0.114 * b;

      // -----------------------------------------------------------------------
      // فقط پیکسل‌های نسبتاً روشن
      // -----------------------------------------------------------------------

      if (luminance > 150) {
        var amount = (luminance - 150) / 105;

        if (amount < 0) {
          amount = 0;
        } else if (amount > 1) {
          amount = 1;
        }

        amount *= s;

        // ---------------------------------------------------------------------
        // Interpolation مستقیم
        // ---------------------------------------------------------------------

        pixel.r = (r + (255 - r) * amount).round();

        pixel.g = (g + (255 - g) * amount).round();

        pixel.b = (b + (255 - b) * amount).round();
      }
    }

    return image;
  }
}
